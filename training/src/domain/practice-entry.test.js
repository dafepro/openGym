import { describe, it, expect } from 'vitest'
import { createStartedSession, reduceSession, getSessionView, validateSession } from './session.js'
import { createPractice, encodePractice, decodePractice } from './practice-builder.js'
import { createTrainingRepository, exportProgress, parseProgressExport } from '../storage/index.js'
import { indexedDB } from 'fake-indexeddb'

const makeDrill = (fields = {}) => ({ id: 'own-touch', title: 'My close touches', instructions: 'Move the ball inside your marked space.', mode: 'practice', sets: 1, side: 'both', restSec: null, media: { id: 'own-touch-help', status: 'unavailable' }, ...fields })
const plan = fields => createPractice('My practice', [makeDrill(fields)], { id: 'personal-practice', revision: 'edition-1' })
const act = (session, type, now, fields = {}) => reduceSession(session, { type, now, id: `command-${type}-${now}`, sessionId: session.id, rowId: session.currentRowId, ...fields })

describe('single-action practice entry and durable work', () => {
  it('starts and records a self-paced drill without a second start, excluding paused help time', async () => {
    const assignment = plan()
    let session = createStartedSession(assignment, { id: 'attempt-own', now: 1000 })
    expect(session.phase).toBe('working')
    expect(getSessionView(session, 6000).practiceSeconds).toBe(5)
    session = act(session, 'PAUSE_PRACTICE', 6000)
    expect(getSessionView(session, 16000).practiceSeconds).toBe(5)
    session = act(session, 'RESUME_PRACTICE', 16000)
    session = act(session, 'DONE', 20000)
    expect(session.rows[0].practiceSeconds).toBe(9)
    session = act(session, 'FINISH', 21000)
    expect(session.status).toBe('completed')
    expect(assignment.drills[0]).not.toHaveProperty('practiceSeconds')
    const repository = createTrainingRepository({ indexedDB, name: 'playbook-entry-roundtrip' })
    const empty = await repository.load()
    await repository.save({ ...empty, sessions: [session] })
    const loaded = await repository.load()
    const restored = parseProgressExport(exportProgress(loaded, { now: 22000 }))
    expect(restored.sessions[0].rows[0].practiceSeconds).toBe(9)
    expect(restored.sessions[0].assignment).toEqual(assignment)
    await repository.close()
  })
  it('starts timed work once and preserves partial actual work when paused and finished early', () => {
    let session = createStartedSession(plan({ mode: 'time', durationSec: 30, sets: 2, restSec: 10 }), { id: 'timed-attempt', now: 1000 })
    session = act(session, 'TICK', 2000)
    session = act(session, 'STOP', 2500)
    expect(session.rows[0].actual).toBe(1.5)
    expect(session.rows[0].status).toBe('stopped')
    session = act(session, 'START', 12000)
    expect(getSessionView(session, 12000).remainingSec).toBe(28.5)
    session = act(session, 'TICK', 13000)
    session = act(session, 'DONE', 13500)
    expect(session.rows[0].actual).toBe(3)
    expect(session.rows[0].prescriptionMet).toBe(false)
    expect(session.phase).toBe('rest')
    expect(session.rows[1].status).toBe('pending')
    expect(validateSession(session)).toBeTruthy()
  })
  it('records a custom repetition target honestly and roundtrips the practice link', () => {
    const assignment = plan({ mode: 'reps', reps: 12, sets: 1, restSec: 0 })
    const shared = decodePractice(encodePractice(assignment), { assignments: [] })
    let session = createStartedSession(shared, { id: 'rep-attempt', now: 1000 })
    expect(session.phase).toBe('working')
    session = act(session, 'DONE', 3000, { actual: 7 })
    session = act(session, 'FINISH', 4000)
    expect(session.rows[0].actual).toBe(7)
    expect(session.rows[0].target).toBe(12)
    expect(session.status).toBe('partial')
  })
  it('can finish an already paused timed set without crediting time spent deciding', () => {
    let session = createStartedSession(plan({ mode: 'time', durationSec: 30, sets: 1, restSec: 0 }), { id: 'paused-attempt', now: 1000 })
    session = act(session, 'TICK', 2000)
    session = act(session, 'STOP', 2500)
    session = act(session, 'DONE', 120000, { actual: 30 })
    expect(session.phase).toBe('complete')
    expect(session.rows[0].actual).toBe(1.5)
    expect(session.rows[0].prescriptionMet).toBe(false)
    const duplicate = act(session, 'DONE', 121000)
    expect(duplicate).toBe(session)
    session = act(session, 'FINISH', 122000)
    expect(session.status).toBe('partial')
    expect(validateSession(session)).toBeTruthy()
  })
  it('does not turn a watch-only reference into athletic work', () => {
    const session = createStartedSession(plan({ mode: 'watch' }), { id: 'watch-attempt', now: 1000 })
    expect(session.phase).toBe('ready')
    expect(session.timer).toBeNull()
    expect(session.practiceTimer).toBeUndefined()
  })
})
