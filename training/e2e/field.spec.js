import { test, expect, capture, noHorizontalOverflow, catalog } from './fixtures.js'

test('field display keeps explicit recording and pause controls reachable', async ({ page }, testInfo) => {
  await page.getByRole('button', { name: 'Start practice', exact: true }).click()
  await page.getByText('Field settings', { exact: true }).click()
  await page.getByRole('button', { name: 'Large display', exact: true }).click()
  await page.getByRole('button', { name: 'Audible cues', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Audible cues', exact: true })).toHaveAttribute('aria-pressed', 'true')
  await page.getByText('Field settings', { exact: true }).click()
  const dock = page.getByRole('region', { name: 'Practice controls' })
  await expect(dock).toHaveAttribute('data-field', 'true')
  await expect(dock.getByText('WORK', { exact: true })).toBeVisible()
  await noHorizontalOverflow(page)
  await page.getByRole('button', { name: 'Pause practice timer', exact: true }).click()
  await expect(dock.getByText('PAUSED', { exact: true })).toBeVisible()
  await capture(page, testInfo, 'field-display')
  await page.getByRole('button', { name: 'Resume practice timer', exact: true }).click()
  await page.getByRole('button', { name: 'Next drill', exact: true }).click()
  await expect(dock).toHaveAttribute('data-phase', 'ready')
  await page.getByRole('button', { name: 'Start set', exact: true }).click()
  await page.getByRole('spinbutton', { name: 'Repetitions completed', exact: true }).fill('2')
  await noHorizontalOverflow(page)
})

test('timed expiry waits for actual-time confirmation before rest', async ({ page }) => {
  const timed = structuredClone(catalog)
  const assignment = timed.assignments.find((item) => item.id === timed.currentAssignmentId)
  assignment.drills = [{ ...assignment.drills[0], mode: 'time', durationSec: 3, sets: 2, restSec: 2 }]
  await page.route('**/api/catalog', (route) => route.fulfill({ json: timed }))
  await page.reload()
  await page.getByRole('button', { name: 'Start practice', exact: true }).click()
  const dock = page.getByRole('region', { name: 'Practice controls' })
  await expect(dock).toHaveAttribute('data-phase', 'review', { timeout: 10000 })
  const actual = page.getByRole('spinbutton', { name: 'Seconds actually completed' })
  await expect(actual).toHaveValue('3')
  await page.waitForTimeout(2200)
  await expect(dock).toHaveAttribute('data-phase', 'review')
  await actual.fill('1')
  await page.getByRole('button', { name: 'Confirm time', exact: true }).click()
  await expect(dock).toHaveAttribute('data-phase', 'rest')
  await expect(dock).toHaveAttribute('data-phase', 'ready')
  await page.waitForTimeout(1200)
  await expect(dock).toHaveAttribute('data-phase', 'ready')
})
