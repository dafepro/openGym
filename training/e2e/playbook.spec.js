  await filters.getByRole('combobox', { name: 'Skill', exact: true }).selectOption('futbol:passing')
  await filters.getByRole('checkbox', { name: 'Only drills with video', exact: true }).check()
  await filters.getByRole('button', { name: /^Show \d+ drill/ }).click()
  await expect(filters).toHaveCount(0)
  await picker.getByRole('button', { name: 'All drills', exact: true }).click()
  await picker.getByRole('button', { name: 'With video', exact: true }).click()
  await expect(picker.getByRole('button', { name: 'With video', exact: true })).toHaveAttribute('aria-pressed', 'true')
  await picker.getByRole('button', { name: `Preview ${firstTitle}`, exact: true }).click()
  const preview = page.getByRole('dialog', { name: firstTitle, exact: true })
  await preview.getByRole('button', { name: 'Back to drill choices', exact: true }).click()
